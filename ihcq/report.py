"""PDF report for a session: every image with its overlays and metrics, the
session table, the configuration, and group statistics if groups were set."""
from __future__ import annotations

import textwrap
from pathlib import Path

import numpy as np
import pandas as pd

BIN_COL = {0: "#4f83ff", 1: "#f6c945", 2: "#ff8b3d", 3: "#ff4d5e"}
METRICS = [("h_score", "H-score"), ("pct_positive", "% positive cells"), ("allred_total", "Allred"), ("irs", "IRS"),
           ("hotspot_pct_positive", "hotspot %"), ("dab_area_fraction_pct", "DAB area %"), ("mean_dab_od_tissue", "mean DAB OD"), ("n_cells", "nuclei")]


def build_report(assets: list, rows: list, stats: dict | None, out_path, title="IHCq report"):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.backends.backend_pdf import PdfPages
    from PIL import Image

    df = pd.DataFrame(rows)
    with PdfPages(out_path) as pdf:
        # ---- cover + table ----
        fig = plt.figure(figsize=(11.69, 8.27)); fig.patch.set_facecolor("white")
        fig.text(0.05, 0.93, title, fontsize=22, weight="bold")
        fig.text(0.05, 0.895, f"{len(df)} image{'s' if len(df) != 1 else ''} · generated by IHCq · chromogenic IHC quantification in optical-density space", fontsize=10, color="#555")
        cols = [c for c, _ in METRICS if c in df.columns]
        show = df[["image"] + cols + [c for c in ("group", "second_stain", "thr_weak", "thr_moderate", "thr_strong") if c in df.columns]].copy()
        for c in cols:
            show[c] = show[c].map(lambda v, c=c: "—" if pd.isna(v) else (f"{v:.0f}" if c in ("n_cells", "allred_total", "irs") else f"{v:.2f}" if c == "mean_dab_od_tissue" else f"{v:.1f}"))
        ax = fig.add_axes([0.03, 0.08, 0.94, 0.78]); ax.axis("off")
        tbl = ax.table(cellText=show.values.tolist(), colLabels=[dict(METRICS).get(c, c) for c in show.columns], loc="upper center", cellLoc="center")
        tbl.auto_set_font_size(False); tbl.set_fontsize(7); tbl.scale(1, 1.25); tbl.auto_set_column_width(list(range(len(show.columns))))
        for (r, c), cell in tbl.get_celld().items():
            cell.set_edgecolor("#ddd")
            if r == 0: cell.set_facecolor("#eef0f7"); cell.set_text_props(weight="bold")
        fig.text(0.05, 0.04, "Cut points are DAB optical density: below weak = 0, then 1+, 2+, 3+. H-score = 1·%1+ + 2·%2+ + 3·%3+. Allred = proportion score + intensity score.", fontsize=7.5, color="#555")
        pdf.savefig(fig); plt.close(fig)

        # ---- per-image pages ----
        for a in assets:
            s = a["summary"]
            fig = plt.figure(figsize=(11.69, 8.27)); fig.patch.set_facecolor("white")
            fig.text(0.04, 0.95, s["image"], fontsize=15, weight="bold")
            fig.text(0.04, 0.92, f"{s['width']}×{s['height']} px · compartment {s['compartment']} · cut points {s['thr_weak']}/{s['thr_moderate']}/{s['thr_strong']} OD · stain: {s['second_stain']}", fontsize=8.5, color="#555")
            panels = [("original", "Original"), ("cells", "Nuclei by bin  (blue 0 · yellow 1+ · orange 2+ · red 3+)"), ("positivity", "Positivity map (per pixel)"), ("stains", "Stain separation: original | hematoxylin | DAB")]
            pos = [[0.04, 0.50, 0.44, 0.40], [0.52, 0.50, 0.44, 0.40], [0.04, 0.06, 0.44, 0.40], [0.52, 0.335, 0.44, 0.14]]
            for (key, cap), p in zip(panels, pos):
                pth = a["images"].get(key)
                if not pth or not Path(pth).exists(): continue
                ax = fig.add_axes(p); im = np.array(Image.open(pth).convert("RGB"))
                if key in ("cells", "positivity") and im.shape[0] > s["height"]: im = im[im.shape[0] - s["height"]:]
                ax.imshow(im); ax.set_title(cap, fontsize=8, loc="left"); ax.axis("off")
            # metrics + histogram
            ax = fig.add_axes([0.52, 0.115, 0.44, 0.205]); ax.axis("off")
            ci = s.get("pct_positive_ci95")
            lines = [f"H-score {s.get('h_score', '—')}    positive {s.get('pct_positive', '—')} %" + (f" (95% CI {ci[0]}–{ci[1]})" if ci else "") + f"    nuclei {s.get('n_cells', '—')}",
                     f"Allred {s.get('allred_total', '—')}    IRS {s.get('irs', '—')}/12    "
                     + (f"hotspot {s['hotspot_pct_positive']} % ({s['hotspot_window']}-cell window)" if s.get("hotspot_pct_positive") is not None else "hotspot — (too few cells)")
                     + f"    profiler zone {s.get('profiler_zone', '—')}",
                     f"1+ {s.get('pct_1plus', '—')} %   2+ {s.get('pct_2plus', '—')} %   3+ {s.get('pct_3plus', '—')} %",
                     f"DAB area {s.get('dab_area_fraction_pct', '—')} %    mean DAB OD {s.get('mean_dab_od_tissue', '—')}    p95 {s.get('p95_dab_od_tissue', '—')}",
                     f"tissue {round((s.get('tissue_fraction') or 0) * 100)} % of field    white point {s.get('white_point_source')}    median nucleus r {s.get('median_nucleus_radius_px')} px"]
            if s.get("group"): lines.insert(0, f"group: {s['group']}")
            if s.get("roi_fraction") is not None: lines.insert(0, f"scored inside a drawn ROI — {round(s['roi_fraction'] * 100)} % of the tissue")
            ax.text(0, 1, "\n".join(lines), fontsize=7, va="top", family="monospace", linespacing=1.45)
            flags = a.get("qc") or []
            if flags:
                line_h = 7 * 1.45 / 72 / (0.205 * 8.27)          # one text line as a fraction of the axes height
                ax.text(0, 1 - line_h * (len(lines) + 0.5), "\n".join(textwrap.fill("! " + f, 120) for f in flags[:3]), fontsize=6, va="top", color="#b25a00", linespacing=1.3)
            cells = a.get("cells")
            if cells is not None and len(cells):
                axh = fig.add_axes([0.60, 0.035, 0.34, 0.06]); od = cells["dab_od"].to_numpy()
                n, edges, patches = axh.hist(od, bins=40, color="#999")
                for p_, e in zip(patches, edges[:-1]):
                    b = (e >= s["thr_weak"]) + (e >= s["thr_moderate"]) + (e >= s["thr_strong"]); p_.set_facecolor(BIN_COL[int(b)])
                for t in (s["thr_weak"], s["thr_moderate"], s["thr_strong"]): axh.axvline(t, color="k", lw=0.6, ls="--")
                axh.set_yticks([]); axh.tick_params(labelsize=6); axh.set_xlabel("DAB OD per cell", fontsize=6.5); axh.spines[["top", "right", "left"]].set_visible(False)
            pdf.savefig(fig); plt.close(fig)

        # ---- statistics ----
        if stats and stats.get("groups"):
            fig = plt.figure(figsize=(11.69, 8.27)); fig.patch.set_facecolor("white")
            fig.text(0.05, 0.94, "Between-group statistics", fontsize=16, weight="bold")
            gnames = list(stats["groups"].keys()); cols_ = [c for c, _ in METRICS if c in df.columns and c != "n_cells"][:5]
            for i, m in enumerate(cols_):
                ax = fig.add_axes([0.06 + (i % 3) * 0.32, 0.50 - (i // 3) * 0.40, 0.26, 0.32])
                data = [pd.to_numeric(df[df["group"] == g][m], errors="coerce").dropna().to_numpy() for g in gnames]
                try:
                    bp = ax.boxplot(data, tick_labels=gnames, widths=0.5, patch_artist=True, showfliers=False)
                except TypeError:  # matplotlib < 3.9
                    bp = ax.boxplot(data, labels=gnames, widths=0.5, patch_artist=True, showfliers=False)
                for patch, col in zip(bp["boxes"], ["#8b7cff", "#d08a3b", "#4f83ff", "#3dd68c", "#ff4d5e", "#f6c945"] * 3): patch.set_facecolor(col); patch.set_alpha(0.35)
                for k, d in enumerate(data): ax.scatter(np.random.default_rng(k).normal(k + 1, 0.05, len(d)), d, s=12, color="#333", zorder=3)
                t = (stats.get("tests") or {}).get(m, {})
                ax.set_title(f"{dict(METRICS)[m]}" + (f"   {t.get('test', '')} p = {t.get('p', float('nan')):.3g}" if t else ""), fontsize=8, loc="left")
                ax.tick_params(labelsize=7); ax.spines[["top", "right"]].set_visible(False)
            fig.text(0.05, 0.05, textwrap.fill(stats.get("note", ""), 160), fontsize=7.5, color="#555")
            pdf.savefig(fig); plt.close(fig)

        # ---- configuration ----
        fig = plt.figure(figsize=(11.69, 8.27)); fig.patch.set_facecolor("white")
        fig.text(0.05, 0.94, "Method", fontsize=16, weight="bold")
        method = ("Images were converted to optical density (OD = −log10 I/I₀, white point from bare glass or supplied) and separated into hematoxylin and DAB "
                  "by colour deconvolution (Ruifrok & Johnston 2001). Tissue was defined as the smoothed total-OD footprint with holes filled. Nuclei were found on the "
                  "background-flattened hematoxylin channel by a distance-transform watershed (optionally StarDist), with strongly stained nuclei recovered by a shape test on compact DAB blobs. "
                  "Each nucleus was scored on its eroded core (nuclear) or on a ring outside it (membrane/cytoplasm) by the chosen per-cell statistic of DAB OD, and binned at the stated cut points. "
                  "H-score = Σ(bin × % cells); Allred = proportion score (0–5) + intensity score (0–3); IRS (Remmele–Stegner) = proportion score (0–3) × intensity score (0–3); "
                  "the 95 % confidence interval on % positive is the Wilson score interval; the hotspot is the highest positive fraction among neighbourhoods of the stated number of nearest cells; DAB area = tissue pixels above the 0/1+ cut. "
                  "The second stain of every image was identified from its fitted stain vector; fields whose second stain is eosin (H&E) carry invalid DAB scores. "
                  "Between-group tests: two groups — Welch t-test and Mann–Whitney U; more — one-way ANOVA and Kruskal–Wallis. Software: IHCq (local, open source).")
        fig.text(0.05, 0.88, textwrap.fill(method, 150), fontsize=8.5, va="top", linespacing=1.5)
        pdf.savefig(fig); plt.close(fig)
    return out_path
